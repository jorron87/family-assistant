// Only user activity extends the timeout. Background refreshes do not.
export function idleReturn(onHome, { target, idleMs = 120_000, schedule = setTimeout, cancel = clearTimeout }) {
  let timer;
  const activity = () => { cancel(timer); timer = schedule(() => { onHome(); activity(); }, idleMs); };
  const events = ["pointerdown", "pointermove", "pointerup", "touchstart", "touchmove", "wheel", "keydown", "input"];
  for (const type of events) target.addEventListener(type, activity, { passive:true, capture:true });
  activity();
  return () => { cancel(timer); for (const type of events) target.removeEventListener(type, activity, { capture:true }); };
}

export function installKiosk(onHome) {
  idleReturn(onHome, { target:document });
  // Some touch drivers emit mouse pointers. Support dragging those as well
  // as Chromium's native touch scrolling, including drags starting on cards.
  let drag;
  let suppressClick = false;
  let lastTouch = -Infinity;
  document.addEventListener("touchstart",()=>{lastTouch=performance.now();drag=null;suppressClick=false;},{capture:true,passive:true});
  document.addEventListener("touchend",()=>{lastTouch=performance.now();},{capture:true,passive:true});
  document.addEventListener("pointerdown", event => {
    suppressClick=false;
    // Never capture compatibility mouse events generated by a touch gesture.
    if (event.pointerType !== "mouse" || event.sourceCapabilities?.firesTouchEvents || performance.now()-lastTouch<800 || event.button !== 0 || event.target.closest("input,select,textarea")) return;
    let scroller=event.target;
    while (scroller && scroller !== document.body) {
      const style=getComputedStyle(scroller);
      if (/(auto|scroll)/.test(style.overflowY) && scroller.scrollHeight > scroller.clientHeight + 2) break;
      scroller=scroller.parentElement;
    }
    if (!scroller || scroller === document.body) return;
    drag={scroller,id:event.pointerId,x:event.clientX,y:event.clientY,top:scroller.scrollTop,left:scroller.scrollLeft,moved:false};
  });
  document.addEventListener("pointermove",event=>{
    if (!drag || event.pointerId !== drag.id) return;
    if (!drag.moved && Math.hypot(event.clientX-drag.x,event.clientY-drag.y)<18) return;
    if (!drag.moved) { drag.moved=true; drag.scroller.setPointerCapture(event.pointerId); }
    event.preventDefault();
    drag.scroller.scrollTop=drag.top+drag.y-event.clientY;
    drag.scroller.scrollLeft=drag.left+drag.x-event.clientX;
  },{passive:false});
  const stop=()=>{if (drag?.moved) suppressClick=true; drag=null;};
  document.addEventListener("pointerup",stop);
  document.addEventListener("pointercancel",()=>{drag=null;suppressClick=false;});
  document.addEventListener("click",event=>{if (suppressClick) { event.preventDefault(); event.stopImmediatePropagation(); suppressClick=false; }},true);
}

// Bound requests and serialize refreshes. Optional diagnostics must not hide
// available calendar data; a force request survives an ongoing background poll.
export function createRefresh(load) {
 let running=null,forceQueued=false;
 return function refresh({force=false}={}) {
  if(running){forceQueued ||= force;return running;}
  running=(async()=>{
   try {
    do {const nextForce=force;forceQueued=false;await load({force:nextForce});force=forceQueued;} while(forceQueued);
   } finally {running=null;forceQueued=false;}
  })();
  return running;
 };
}
